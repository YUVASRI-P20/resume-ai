"""
Object storage abstraction for resume files.

Two backends are supported, selected via `settings.STORAGE_BACKEND`:
  - "local": writes to disk under settings.LOCAL_STORAGE_DIR (default; good
    for dev/self-hosted deployments).
  - "supabase": uploads to a Supabase Storage bucket via the Supabase REST API.

Both implement the same interface so the rest of the app never needs to know
which backend is active.
"""
from __future__ import annotations

import os
import uuid
from abc import ABC, abstractmethod

import httpx

from app.core.config import settings
from app.core.exceptions import StorageError
from app.core.logging import get_logger

logger = get_logger(__name__)


class BaseStorageService(ABC):
    @abstractmethod
    def upload(self, content: bytes, user_id: uuid.UUID, filename: str) -> str:
        """Store the file and return a storage_path/key that can later be used to fetch or delete it."""

    @abstractmethod
    def download(self, storage_path: str) -> bytes:
        """Retrieve the raw file content."""

    @abstractmethod
    def delete(self, storage_path: str) -> None:
        """Delete the stored file. Should not raise if already missing."""


class LocalStorageService(BaseStorageService):
    def __init__(self, base_dir: str | None = None):
        self.base_dir = base_dir or settings.LOCAL_STORAGE_DIR
        os.makedirs(self.base_dir, exist_ok=True)

    def _full_path(self, storage_path: str) -> str:
        # storage_path is always relative and generated by us -- never trust client input here.
        full = os.path.normpath(os.path.join(self.base_dir, storage_path))
        if not full.startswith(os.path.normpath(self.base_dir)):
            raise StorageError("Invalid storage path.")
        return full

    def upload(self, content: bytes, user_id: uuid.UUID, filename: str) -> str:
        user_dir = os.path.join(self.base_dir, str(user_id))
        os.makedirs(user_dir, exist_ok=True)
        unique_name = f"{uuid.uuid4().hex}_{filename}"
        storage_path = os.path.join(str(user_id), unique_name)
        full_path = os.path.join(self.base_dir, storage_path)
        try:
            with open(full_path, "wb") as f:
                f.write(content)
        except OSError as exc:
            logger.exception("Failed to write resume file to local storage")
            raise StorageError("Failed to store resume file.") from exc
        return storage_path

    def download(self, storage_path: str) -> bytes:
        full_path = self._full_path(storage_path)
        try:
            with open(full_path, "rb") as f:
                return f.read()
        except OSError as exc:
            raise StorageError("Failed to read resume file.") from exc

    def delete(self, storage_path: str) -> None:
        full_path = self._full_path(storage_path)
        try:
            if os.path.exists(full_path):
                os.remove(full_path)
        except OSError as exc:
            logger.warning("Failed to delete resume file %s: %s", storage_path, exc)


class SupabaseStorageService(BaseStorageService):
    def __init__(self):
        if not settings.SUPABASE_URL or not settings.SUPABASE_SERVICE_KEY:
            raise StorageError("Supabase storage is not configured (SUPABASE_URL / SUPABASE_SERVICE_KEY).")
        self.base_url = settings.SUPABASE_URL.rstrip("/")
        self.bucket = settings.SUPABASE_BUCKET
        self.headers = {
            "Authorization": f"Bearer {settings.SUPABASE_SERVICE_KEY}",
            "apikey": settings.SUPABASE_SERVICE_KEY,
        }

    def upload(self, content: bytes, user_id: uuid.UUID, filename: str) -> str:
        unique_name = f"{uuid.uuid4().hex}_{filename}"
        storage_path = f"{user_id}/{unique_name}"
        url = f"{self.base_url}/storage/v1/object/{self.bucket}/{storage_path}"
        try:
            resp = httpx.post(
                url,
                headers={**self.headers, "Content-Type": "application/pdf"},
                content=content,
                timeout=30,
            )
            resp.raise_for_status()
        except httpx.HTTPError as exc:
            logger.exception("Supabase upload failed")
            raise StorageError("Failed to upload resume to storage.") from exc
        return storage_path

    def download(self, storage_path: str) -> bytes:
        url = f"{self.base_url}/storage/v1/object/{self.bucket}/{storage_path}"
        try:
            resp = httpx.get(url, headers=self.headers, timeout=30)
            resp.raise_for_status()
        except httpx.HTTPError as exc:
            raise StorageError("Failed to download resume from storage.") from exc
        return resp.content

    def delete(self, storage_path: str) -> None:
        url = f"{self.base_url}/storage/v1/object/{self.bucket}/{storage_path}"
        try:
            httpx.delete(url, headers=self.headers, timeout=30)
        except httpx.HTTPError as exc:
            logger.warning("Failed to delete resume from Supabase: %s", exc)


def get_storage_service() -> BaseStorageService:
    if settings.STORAGE_BACKEND == "supabase":
        return SupabaseStorageService()
    return LocalStorageService()
